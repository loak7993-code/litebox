//! Screen device: a plain RGBA framebuffer the framework's view shim draws
//! into, and agents read as PNG. Lives in core so the VM has no graphics
//! dependency and snapshots capture it as plain bytes.

#[derive(Debug, Clone)]
pub struct Screen {
    pub width: u32,
    pub height: u32,
    pub buf: Vec<u8>,
    pub version: u64,
}

impl Screen {
    pub fn new(width: u32, height: u32) -> Self {
        Screen { width, height, buf: vec![0; (width as usize) * (height as usize) * 4], version: 0 }
    }

    pub fn clear(&mut self, rgba: [u8; 4]) {
        for px in self.buf.as_chunks_mut::<4>().0 {
            px.copy_from_slice(&rgba);
        }
        self.version += 1;
    }

    pub fn set(&mut self, x: u32, y: u32, rgba: [u8; 4]) {
        if x >= self.width || y >= self.height {
            return;
        }
        let i = ((y * self.width + x) * 4) as usize;
        self.buf[i..i + 4].copy_from_slice(&rgba);
    }

    pub fn fill_rect(&mut self, x: u32, y: u32, w: u32, h: u32, rgba: [u8; 4]) {
        let x1 = x.saturating_add(w).min(self.width);
        let y1 = y.saturating_add(h).min(self.height);
        for yy in y..y1 {
            for xx in x..x1 {
                self.set(xx, yy, rgba);
            }
        }
        self.version += 1;
    }

    pub fn bump(&mut self) {
        self.version += 1;
    }
}

