impl Screen {
    /// Draw ASCII text with a scale factor; returns x advance.
    pub fn draw_text(&mut self, x: u32, y: u32, text: &str, scale: u32, rgba: [u8; 4]) -> u32 {
        let mut cx = x;
        for ch in text.chars() {
            let idx = (ch as usize).wrapping_sub(32);
            if idx >= 95 {
                cx += 6 * scale;
                continue;
            }
            let glyph = FONT5X7[idx];
            for (col, bits) in glyph.iter().enumerate() {
                for row in 0..7 {
                    if bits & (1 << row) != 0 {
                        for sx in 0..scale {
                            for sy in 0..scale {
                                self.set(cx + col as u32 * scale + sx, y + row as u32 * scale + sy, rgba);
                            }
                        }
                    }
                }
            }
            cx += 6 * scale;
        }
        self.version += 1;
        cx
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn text_draws_dark_pixels() {
        let mut s = Screen::new(64, 16);
        s.draw_text(2, 4, "Hi", 1, [255, 0, 0, 255]);
        let red = s.buf.chunks(4).any(|p| p == [255, 0, 0, 255]);
        assert!(red, "glyph pixels must appear");
        s.clear([0, 0, 0, 255]);
        assert!(!s.buf.chunks(4).any(|p| p == [255, 0, 0, 255]));
    }
}
